"""
Reproduce Fig. 7: standard deviation of the response of each 3x3 layer on the CIFAR-10 test set.
The response is measured after BN and before ReLU / addition (paper, Sec. 4.2), which for a
ResNet is the size of the learned residual function. No training needed: it uses saved models.

    python layer_responses.py                      # uses seed 0 of every finished A-shortcut run
    python layer_responses.py --seed 1 --runs runs --out results

Writes results/fig7_layer_std.png (top: original order, bottom: sorted) and results/fig7_layer_std.csv
"""
import argparse
import csv
import glob
import json
import os

import numpy as np
import torch
import torchvision
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from models import build_model

COLORS = {20: "#c9b200", 32: "#00b5d8", 44: "#22aa22", 56: "#e02020", 110: "#111111"}


@torch.no_grad()
def layer_stds(model, x):
    """Std of the output of every 3x3 conv's BN (first conv, then bn1 and bn2 of each block)."""
    bns = [model.bn1] + [m for blk in model.layers for m in (blk.bn1, blk.bn2)]
    sums = [0.0] * len(bns); sq = [0.0] * len(bns); count = [0] * len(bns)
    hooks = []
    for k, bn in enumerate(bns):
        def hook(_, __, out, k=k):
            o = out.double()
            sums[k] += o.sum().item(); sq[k] += (o * o).sum().item(); count[k] += o.numel()
        hooks.append(bn.register_forward_hook(hook))
    model.eval()
    for i in range(0, len(x), 500):
        model(x[i:i + 500])
    for h in hooks:
        h.remove()
    return [float(np.sqrt(s2 / c - (s / c) ** 2)) for s, s2, c in zip(sums, sq, count)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs"); ap.add_argument("--out", default="results")
    ap.add_argument("--data-dir", default="./data"); ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    dev = "cuda" if torch.cuda.is_available() else "cpu"

    tr = torchvision.datasets.CIFAR10(a.data_dir, train=True, download=True)
    te = torchvision.datasets.CIFAR10(a.data_dir, train=False, download=True)
    mean = torch.tensor(tr.data).permute(0, 3, 1, 2).float().div(255).mean(0, keepdim=True)
    x = (torch.tensor(te.data).permute(0, 3, 1, 2).float().div(255) - mean).to(dev)

    results = []
    for res_path in sorted(glob.glob(os.path.join(a.runs, "*", "result.json"))):
        r = json.load(open(res_path))
        cfg = json.load(open(os.path.join(os.path.dirname(res_path), "config.json")))
        if (r["seed"] != a.seed or r["shortcut"] != "A" or r.get("eval_set") != "test10k"
                or cfg.get("tag") or cfg.get("no_amp") or cfg.get("iters", 64000) != 64000):
            continue  # main setting only: option A, mixed precision, full-length, no tag
        model = build_model(r["arch"], r["depth"], r["shortcut"]).to(dev)
        model.load_state_dict(torch.load(os.path.join(os.path.dirname(res_path), "final.pt"), map_location=dev))
        results.append((r["arch"], r["depth"], layer_stds(model, x)))
        print(f"{r['arch']}-{r['depth']}: mean layer std {np.mean(results[-1][2]):.3f}")
    if not results:
        raise SystemExit("No finished runs with that seed found.")

    with open(os.path.join(a.out, "fig7_layer_std.csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["model", "layer_index", "std"])
        for arch, d, s in results:
            for i, v in enumerate(s, 1):
                w.writerow([f"{arch}-{d}", i, f"{v:.5f}"])

    with open(os.path.join(a.out, "numbers_fig7.tex"), "w") as f:
        f.write("% Generated by layer_responses.py. Do not edit by hand.\n")
        f.write(r"\providecommand{\lstd}[2]{\ifcsname lstd-#1-#2\endcsname\csname lstd-#1-#2\endcsname"
                r"\else\textcolor{red}{[#1-#2 missing]}\fi}" + "\n")
        for arch, d, s in results:
            f.write(rf"\expandafter\def\csname lstd-{arch}-{d}\endcsname{{{np.mean(s):.3f}}}" + "\n")

    fig, axes = plt.subplots(2, 1, figsize=(6, 5))
    for arch, d, s in sorted(results, key=lambda t: (t[0] != "plain", t[1])):
        style = "--" if arch == "plain" else "-"
        label = f"{'plain' if arch == 'plain' else 'ResNet'}-{d}"
        idx = np.arange(1, len(s) + 1)
        axes[0].plot(idx, s, style, color=COLORS.get(d), label=label)
        axes[1].plot(idx, sorted(s, reverse=True), style, color=COLORS.get(d), label=label)
    axes[0].set_xlabel("layer index (original)"); axes[1].set_xlabel("layer index (sorted by magnitude)")
    for ax in axes:
        ax.set_ylabel("std"); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(os.path.join(a.out, "fig7_layer_std.png"), dpi=300)
    print(f"Wrote {a.out}/fig7_layer_std.png")


if __name__ == "__main__":
    main()
